/**
 * Retrieval eval — P-023 §7 step 7, the measurement DD-070 §8's rationale
 * demands ("the memory-layer core still lacked a measured retrieval win").
 *
 * Compares five retrieval routes over this repo's live corpus, on the frozen
 * query set in queries.yaml:
 *
 *   hybrid   — the real `search()` (FTS5 BM25 + brute-force cosine, RRF)
 *   fts      — keyword leg alone   (mirrors search.ts keywordLeg's SQL)
 *   vector   — vector leg alone    (mirrors search.ts vectorLeg)
 *   rg-rank  — grep baseline, generous: mechanical keyword extraction,
 *              files ranked by (distinct terms matched, total match count)
 *   rg-walk  — grep baseline, honest transcript: one `rg -in` OR-run,
 *              results in path-sorted output order
 *
 * The systems, the grep reimplementation and the metrics live in engine.ts,
 * shared with run-external-eval.ts — this file is the this-repo binding:
 * the frozen query set, golds named as record ids, and report.md.
 *
 * Metrics: Hit@1/3/5/10, MRR@10, tokens-to-locate (hybrid + rg-walk only —
 * the two end-to-end consumer surfaces; see README.md for definitions).
 *
 * Run:  npx tsx tests/eval/run-retrieval-eval.ts
 * Emits tests/eval/report.md and a stdout summary. Deterministic: same
 * corpus + same query set → same report (rg runs use --sort path).
 *
 * Deliberately NOT part of `npm test` (needs the real ONNX embedder and a
 * fresh cache — run `docdog index` first).
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";
import { findProjectRoot, loadConfig } from "../../src/config/loader.js";
import { openCacheRead } from "../../src/storage/cache.js";
import {
  buildReport,
  createEngine,
  printSummary,
  SYSTEMS,
  type EvalQuery,
  type QueryOutcome,
} from "./engine.js";

// ─── Setup ──────────────────────────────────────────────────────────────────

const evalDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = findProjectRoot() ?? process.cwd();
const config = loadConfig(projectRoot);
const queries = (
  parseYaml(readFileSync(join(evalDir, "queries.yaml"), "utf8")) as {
    queries: EvalQuery[];
  }
).queries;

const handle = openCacheRead(projectRoot);
const engine = createEngine({ projectRoot, config, db: handle.db, goldMode: "id" });

// Sanity: every gold id must exist in the corpus, or the eval is measuring
// against a phantom. This set is frozen against ids this repo controls, so an
// unresolved gold is a broken query set rather than a corpus-config gap —
// fail loudly rather than reporting it (the external runner does the latter).
for (const q of queries) {
  const { unresolved } = engine.resolveGold(q);
  if (unresolved.length > 0) {
    throw new Error(`${q.id}: gold record "${unresolved[0]}" not found in the cache`);
  }
}

// ─── Run ────────────────────────────────────────────────────────────────────

const outcomes: QueryOutcome[] = [];
console.log(`Retrieval eval: ${queries.length} queries over ${engine.recordCount} records\n`);

for (const q of queries) {
  const systems = await engine.run(q);
  outcomes.push({ q, systems });
  const marks = SYSTEMS.map(
    (s) => `${s}=${systems[s].goldRank === null ? "—" : systems[s].goldRank}`,
  ).join(" ");
  console.log(`${q.id} [${q.category}] ${marks}`);
}

handle.close();

// ─── Report ─────────────────────────────────────────────────────────────────

const gitSha =
  spawnSync("git", ["rev-parse", "--short", "HEAD"], {
    cwd: projectRoot,
    encoding: "utf8",
  }).stdout?.trim() ?? "unknown";
const today = new Date().toISOString().slice(0, 10);

const report = buildReport({
  title: `Retrieval eval report — ${today}`,
  provenance: [
    `Corpus: ${engine.recordCount} records @ \`${gitSha}\` · embed: \`${config.embed.provider}/${config.embed.model}\` · ` +
      `query set: \`tests/eval/queries.yaml\` (${queries.length} queries) · depth: top-10`,
    `Generated by \`npx tsx tests/eval/run-retrieval-eval.ts\` — see README.md for method.`,
  ],
  outcomes,
  unresolved: [],
});

const reportPath = join(evalDir, "report.md");
mkdirSync(dirname(reportPath), { recursive: true });
writeFileSync(reportPath, report, "utf8");

printSummary(outcomes);
console.log(`\nReport written to ${reportPath}`);
